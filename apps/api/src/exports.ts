import type { Claim, Summary, Comparison } from '@paperlens/shared';
import { summaryFields } from '@paperlens/shared';
export function markdownExport(
  project: string,
  summaries: { paperId: string; output: Summary }[],
  comparison: Comparison,
  gaps: { suggestions: Claim[] },
  origin: string,
) {
  const titles = Object.fromEntries(summaries.map((s) => [s.paperId, s.output.title]));
  const claim = (c: Claim) =>
    `${c.kind === 'suggestion' ? 'AI-generated suggestion: ' : c.kind === 'interpretation' ? 'AI interpretation: ' : ''}${c.text} ${c.citations.map((x) => `[${titles[x.paperId] || x.paperId}, PDF p. ${x.page}](${origin}/api/v1/papers/${x.paperId}/file#page=${x.page})`).join(' ')}`;
  const out = [
    `# ${project}`,
    `Generated by PaperLens. Citations use physical PDF page numbers. Source links require sign-in. Citation validation does not guarantee scientific correctness.`,
    '## Overall synthesis',
    claim(comparison.synthesis),
  ];
  for (const s of summaries) {
    out.push(`## ${s.output.title}`, `${s.output.authors} · ${s.output.year} · ${s.output.venue}`);
    for (const field of summaryFields) out.push(`### ${field}`, claim(s.output[field]));
  }
  out.push('## Comparison');
  for (const row of comparison.rows) {
    out.push(`### ${row.dimension}`);
    for (const cell of row.cells) out.push(`**${titles[cell.paperId]}**: ${claim(cell.claim)}`);
  }
  out.push(
    '## Discussion',
    ...comparison.discussion.map(claim),
    '## Relationships',
    ...comparison.relationships.map(claim),
    '## Potential research directions (AI-generated)',
    ...gaps.suggestions.map(claim),
  );
  return out.join('\n\n');
}
